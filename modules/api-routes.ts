/// <reference types="node" />
import { readdirSync } from 'node:fs'
import { join, relative } from 'node:path'
import { addTypeTemplate, defineNuxtModule } from '@nuxt/kit'

/**
 * Types for `$fetch('/api/…')` calls that the browser-side router answers (app/api/router.ts): the same
 * `InternalApi` entries Nitro generates for server routes, built from the handlers in app/api/routes.
 */
export default defineNuxtModule({
  meta: { name: 'api-routes' },
  setup(_, nuxt) {
    const root = join(nuxt.options.srcDir, 'api/routes')

    // Nuxt's auto-imported `$fetch` is `export const $fetch = globalThis.$fetch`, frozen when that file first loads,
    // before the api-router plugin swaps in the router. Delegate at call time so every `$fetch('/api/…')` is routed.
    nuxt.hook('app:templates', (app) => {
      const fetchTemplate = app.templates.find(t => t.filename === 'fetch.mjs')
      if (!fetchTemplate) return
      const original = fetchTemplate.getContents!
      fetchTemplate.getContents = async (data) => {
        const source = await original(data)
        return source.replace(
          /export const \$fetch = globalThis\.\$fetch\s*$/m,
          'export const $fetch = new Proxy(function () {}, { apply: (_, _this, args) => globalThis.$fetch(...args), get: (_, key) => globalThis.$fetch[key] })'
        )
      }
    })

    const walk = (dir: string): string[] =>
      readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.ts') ? [join(dir, e.name)] : [])

    addTypeTemplate({
      filename: 'types/api-routes.d.ts',
      getContents: ({ nuxt: n }) => {
        const entries = new Map<string, string[]>()
        for (const file of walk(root)) {
          const rel = relative(root, file).replace(/\.ts$/, '')
          const m = /^(.*?)(?:\.(get|post|put|patch|delete))?$/.exec(rel)!
          const segments = m[1]!.split('/').filter(s => s !== 'index')
          const route = '/api/' + segments.map(s => s.replace(/^\[\.\.\..+\]$/, '**').replace(/^\[(.+)\]$/, ':$1')).join('/')
          const type = `Simplify<Serialize<Awaited<ReturnType<typeof import('${relative(join(n.options.buildDir, 'types'), file).replace(/\.ts$/, '')}').default>>>>`
          const methods = m[2] ? [m[2]] : ['get', 'post', 'put', 'patch', 'delete']
          entries.set(route.replace(/\/$/, ''), [...(entries.get(route.replace(/\/$/, '')) ?? []), ...methods.map(x => `'${x}': ${type}`)])
        }
        return `// Generated by modules/api-routes.ts
import type { Serialize, Simplify } from 'nitropack/types'
declare module 'nitropack/types' {
  type Awaited<T> = T extends PromiseLike<infer U> ? Awaited<U> : T
  interface InternalApi {
${[...entries].map(([route, items]) => `    '${route}': { ${items.join('; ')} }`).join('\n')}
  }
}
export {}
`
      }
    })
  }
})
